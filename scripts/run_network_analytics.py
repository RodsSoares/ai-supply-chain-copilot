"""Executa o motor da rede e exporta resultados (CSV para BI + resumo em Markdown).

Uso:
    python scripts/run_network_analytics.py [--data DIR] [--output DIR]

Saídas:
    output/network/*.csv                       — modelo de dados para Power BI
    reports/network/network_analytics_summary.md — resumo executivo gerado (números do motor)
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from src.analytics.network import budget, emissions, forecasting, planning, variance  # noqa: E402
from src.analytics.network.repository import carregar_de_csv  # noqa: E402


def brl(valor: float) -> str:
    return f"R$ {valor:,.0f}"


def pct(valor: float) -> str:
    return f"{valor * 100:.1f}%"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=Path("data/synthetic/transportation/network"))
    parser.add_argument("--output", type=Path, default=Path("output/network"))
    parser.add_argument("--report", type=Path, default=Path("reports/network/network_analytics_summary.md"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    args.report.parent.mkdir(parents=True, exist_ok=True)

    dados = carregar_de_csv(args.data)

    # Planos e orçamentos
    p26 = planning.planejar_cenario(dados, "PLAN_2026")
    p27 = planning.planejar_cenario(dados, "BUDGET_2027")
    l26 = budget.orcamento(dados, "PLAN_2026", p26)
    l27 = budget.orcamento(dados, "BUDGET_2027", p27)
    t26, t27 = budget.totais(l26), budget.totais(l27)
    ponte = budget.ponte_orcamento(p26, l26, p27, l27)
    ajustes = budget.relatorio_ajustes(dados, "BUDGET_2027", l27)

    # What-ifs
    wi_max = planning.rodar_what_if(dados, "BUDGET_2027", [{"parameter_key": "frequency_basis", "value": "MAX"}])
    wi_p75 = planning.rodar_what_if(dados, "BUDGET_2027", [{"parameter_key": "frequency_basis", "value": "P75"}])
    consolidacao = planning.candidatos_consolidacao(dados, "BUDGET_2027", p27)
    sem_demanda = planning.rotas_sem_demanda(p27)

    # Forecast
    bt = forecasting.backtest(dados)
    bt_rede = forecasting.resumo_rede_backtest(bt).set_index("model")
    bt_rotas = forecasting.resumir_backtest(bt)
    acc = {n: forecasting.acuracia_forecast(dados, "BUDGET_2026", n) for n in ("NETWORK", "ROUTE", "STORE")}
    wape_nivel = {n: float(a["abs_error"].sum() / a["actual"].sum()) for n, a in acc.items()}
    vies_rede = float(acc["NETWORK"]["bias"].iloc[0])

    # Plano vs realizado, extras, transportadoras, emissões
    pv = variance.plano_vs_realizado(dados, "PLAN_2026", p26)
    extras = variance.analise_extras(dados, inicio="2025-12-29")
    carriers = variance.desempenho_transportadoras(dados)
    e27 = emissions.emissoes_plano(dados, p27)
    e_tot = emissions.total_emissoes(e27)
    e_max = emissions.total_emissoes(emissions.emissoes_plano(dados, planning.planejar_cenario(
        dados, "BUDGET_2027", [{"parameter_key": "frequency_basis", "value": "MAX"}])))

    # Exportação para BI
    exportar = {
        "plan_2026_weekly": p26.drop(columns=["explanation_json"]),
        "budget_2027_weekly": p27.drop(columns=["explanation_json"]),
        "budget_lines_2026": l26,
        "budget_lines_2027": l27,
        "budget_bridge_steps": pd.DataFrame(ponte["steps"]),
        "budget_bridge_by_route": ponte["by_route"],
        "management_adjustments": ajustes,
        "plan_vs_actual_by_route": pv["detail"],
        "forecast_backtest_by_route": bt_rotas,
        "forecast_accuracy_budget_2026_route": acc["ROUTE"],
        "forecast_accuracy_budget_2026_store": acc["STORE"],
        "consolidation_candidates": consolidacao,
        "emissions_2027_by_route": emissions.resumo_emissoes(e27),
        "extras_by_reason": extras,
        "carrier_performance": carriers,
        "route_summary_2027": planning.resumo_por_rota(p27),
    }
    for nome, df in exportar.items():
        df.to_csv(args.output / f"{nome}.csv", index=False, lineterminator="\n")

    passos = {s["step"]: s["amount_brl"] for s in ponte["steps"]}
    rb = planning.resumo_rede(p27)
    pvt = pv["total"]
    linhas = [
        "# Network Planning & Budget — Analytics Summary",
        "",
        "> Generated by `scripts/run_network_analytics.py` from the synthetic dataset `network_v1`.",
        "> All data is 100% synthetic. Numbers come from the deterministic engine; nothing is typed by hand.",
        "",
        "## Budget 2027",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Model budget | {brl(t27['model_budget'])} |",
        f"| Approved management adjustments | {brl(t27['adjustments'])} ({pct(t27['adjustment_share'])} of final) |",
        f"| Final budget | {brl(t27['final_budget'])} |",
        f"| Volume (pieces) | {t27['volume']:,.0f} |",
        f"| Final cost per piece | R$ {t27['final_budget'] / t27['volume']:.3f} |",
        f"| Road utilization | {pct(rb['road_utilization'])} |",
        f"| Route-weeks with overflow | {pct(rb['overflow_rate'])} ({rb['overflow_trips']} spot trips, {brl(rb['overflow_cost'])}) |",
        "",
        "## Budget bridge — Plan 2026 → Budget 2027",
        "",
        "| Step | Amount |",
        "|---|---:|",
        *[f"| {k.replace('_', ' ').capitalize()} | {brl(v)} |" for k, v in passos.items()],
        "",
        f"Residual: {ponte['residual']:.6f} (steps sum exactly to the variance).",
        "",
        "## Frequency policy what-if (Budget 2027)",
        "",
        "| Policy | Δ trips | Δ spot trips | Δ transport cost | Δ tCO₂e |",
        "|---|---:|---:|---:|---:|",
        f"| P75 instead of MEAN | {wi_p75['delta']['total_trips']:+,.0f} | {wi_p75['delta']['overflow_trips']:+,.0f} | {brl(wi_p75['delta']['transport_cost'])} | — |",
        f"| MAX (size for peak) | {wi_max['delta']['total_trips']:+,.0f} | {wi_max['delta']['overflow_trips']:+,.0f} | {brl(wi_max['delta']['transport_cost'])} | {e_max['t_co2e'] - e_tot['t_co2e']:+,.1f} |",
        "",
        "Fixed monthly frequency plus spot overflow is cheaper than sizing the fleet for the weekly peak.",
        "",
        "## Consolidation",
        "",
        f"- Routes without demand in 2027 (candidates for deactivation): {', '.join(sem_demanda) or 'none'}",
        *[f"- {r.route_id}: utilization {pct(r.current_utilization)} → best option {r.best_vehicle} with min. frequency {r.best_frequency_min}/week, "
          f"saving {brl(r.annual_saving)} ({r.service_change})" for r in consolidacao.itertuples()],
        "",
        "## Forecast",
        "",
        f"- Budget 2026 forecast bias (network): {pct(vies_rede)} (optimistic growth assumption).",
        f"- Budget 2026 WAPE: network {pct(wape_nivel['NETWORK'])}, route {pct(wape_nivel['ROUTE'])}, store {pct(wape_nivel['STORE'])}.",
        f"- Backtest (13-week horizon) WAPE: Holt-Winters {pct(bt_rede.loc['HOLT_WINTERS', 'wape'])}, "
        f"seasonal naïve {pct(bt_rede.loc['SEASONAL_NAIVE', 'wape'])}, moving average {pct(bt_rede.loc['MOVING_AVERAGE', 'wape'])}.",
        f"- Best model per route: {bt_rotas['best_model'].value_counts().to_dict()}.",
        "",
        "## Plan vs. actual 2026 (YTD)",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Period | {pvt['period'][0]} → {pvt['period'][1]} |",
        f"| Plan transport cost | {brl(pvt['plan_cost'])} |",
        f"| Actual transport cost | {brl(pvt['actual_cost'])} |",
        f"| Variance | {brl(pvt['variance'])} ({pct(pvt['variance_pct'])}) |",
        f"| Volume effect | {brl(pvt['volume_effect'])} |",
        f"| Efficiency effect | {brl(pvt['efficiency_effect'])} |",
        f"| Rate effect (incl. spot mix) | {brl(pvt['rate_effect'])} |",
        f"| Extras plan vs actual | {brl(pvt['plan_extras'])} vs {brl(pvt['actual_extras'])} |",
        "",
        "## Service and sustainability",
        "",
        *[f"- {r.carrier_id}: on-time {pct(r.on_time_rate)} vs target {pct(r.on_time_target)}" for r in carriers.itertuples()],
        f"- Budget 2027 emissions: {e_tot['t_co2e']:,.0f} tCO₂e, {e_tot['kg_co2e_per_piece'] * 1000:.0f} g CO₂e/piece; "
        f"air routes = {pct(e_tot['air_share_of_emissions'])} of emissions (illustrative factors).",
        "",
    ]
    args.report.write_text("\n".join(linhas), encoding="utf-8")
    print(f"CSV: {args.output}  |  Report: {args.report}")


if __name__ == "__main__":
    main()
