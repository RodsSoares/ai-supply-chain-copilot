"""Executa a política dinâmica de estoque (v2.6) e exporta resultados.

Uso:
    python scripts/run_inventory_policy.py

Saídas:
    output/inventory_policy/*.csv
    reports/inventory/inventory_policy_summary.md (números gerados pelo motor)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from src.analytics.inventory_policy import safety_stock as ss  # noqa: E402
from src.synthetic.inventory_demand_generator import CAMINHO_SAIDA, carregar_config, carregar_erp  # noqa: E402


def brl(v: float) -> str:
    return f"R$ {v:,.0f}"


def main() -> None:
    saida, relatorio = Path("output/inventory_policy"), Path("reports/inventory/inventory_policy_summary.md")
    saida.mkdir(parents=True, exist_ok=True)
    relatorio.parent.mkdir(parents=True, exist_ok=True)

    erp, demanda, config = carregar_erp(), pd.read_csv(CAMINHO_SAIDA), carregar_config()
    pol = ss.calcular_politica(erp, demanda, config)
    c = ss.comparar_politicas(pol)
    cob = ss.cobertura_historica(pol, demanda)
    curva = ss.curva_servico_capital(erp, demanda, config)

    pol.to_csv(saida / "dynamic_policy_by_sku.csv", index=False, lineterminator="\n")
    cob.to_csv(saida / "empirical_service_level_by_sku.csv", index=False, lineterminator="\n")
    curva.to_csv(saida / "service_capital_curve.csv", index=False, lineterminator="\n")

    cob_abc = cob.groupby("classe_abc")[["service_level", "empirical_cycle_service_level"]].mean()
    acoes = list(ss.ACOES)
    linhas = [
        "# Inventory — Dynamic Policy vs. Static Min/Max",
        "",
        "> Generated by `scripts/run_inventory_policy.py`. Data is 100% synthetic (`inventory_demand_v1`).",
        "> The static min/max recommendations used by the current Copilot are preserved; this is a side-by-side comparison.",
        "",
        "## Policy",
        "",
        "`SS = z(service level) × sqrt(LT × σd² + d̄² × σLT²)` · `ROP = d̄ × LT + SS` · `MAX = ROP + d̄ × 4 weeks`",
        "",
        "| Class | SKUs | Service level | Empirical cycle service level | Safety stock value | Actions changed |",
        "|---|---:|---:|---:|---:|---:|",
        *[f"| {r['classe_abc']} | {r['skus']} | {r['service_level']:.0%} | {cob_abc.loc[r['classe_abc'], 'empirical_cycle_service_level']:.1%} | "
          f"{brl(r['safety_stock_value'])} | {r['actions_changed']} |" for r in c["by_abc"]],
        "",
        "## Recommendation changes (rows = static, columns = dynamic)",
        "",
        "| Static \\ Dynamic | " + " | ".join(acoes) + " |",
        "|---|" + "---:|" * len(acoes),
        *[f"| {s} | " + " | ".join(str(c["transition_matrix"][s][d]) for d in acoes) + " |" for s in acoes],
        "",
        f"**{c['actions_changed']} of {c['skus']} SKUs** change recommendation when min/max is replaced by a service-level policy.",
        "",
        "## Capital",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Current inventory value | {brl(c['current_inventory_value'])} |",
        f"| Static policy — target average inventory ((min + max) / 2) | {brl(c['static_target_avg_inventory_value'])} |",
        f"| Dynamic policy — target average inventory (SS + cycle stock) | {brl(c['dynamic_target_avg_inventory_value'])} |",
        f"| Safety stock value | {brl(c['safety_stock_value'])} |",
        f"| Dynamic replenishment orders now | {brl(c['dynamic_order_value'])} |",
        f"| Dynamic excess above order-up-to | {brl(c['dynamic_excess_value'])} |",
        "",
        "## Service level × safety stock capital (same level for all classes)",
        "",
        "| Service level | Safety stock value | Reorder alerts |",
        "|---:|---:|---:|",
        *[f"| {r.service_level:.0%} | {brl(r.safety_stock_value)} | {r.reorder_alerts} |" for r in curva.itertuples()],
        "",
        "Notes: the empirical service level uses the last 52 weeks with a fixed lead time, while the policy also",
        "buffers lead-time variability — so the empirical figure is expected to sit above the target.",
        "",
    ]
    relatorio.write_text("\n".join(linhas), encoding="utf-8")
    print(f"CSV: {saida}  |  Report: {relatorio}")


if __name__ == "__main__":
    main()
